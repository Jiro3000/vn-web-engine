import {spawnSync} from 'node:child_process';
import {mkdtemp, rm, readFile, writeFile} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {fileURLToPath} from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const dir = await mkdtemp(join(tmpdir(), 'vn-freetype-'));
try {
  const modules = [
    'base/ftbase',
    'base/ftinit',
    'base/ftdebug',
    'base/ftbitmap',
    'base/ftsynth',
    'sfnt/sfnt',
    'truetype/truetype',
    'cff/cff',
    'smooth/smooth',
    'raster/raster',
    'psnames/psnames',
    'pshinter/pshinter',
    'psaux/psaux',
  ];
  const exports = [
    'malloc',
    'free',
    'font_init',
    'font_done',
    'font_open',
    'font_close',
    'font_size',
    'font_info',
    'font_glyph',
    'font_glyph_info',
    'font_error',
    'font_version',
    'font_char_index',
  ];
  const output = join(dir, 'freetype.wasm');
  const result = spawnSync(
    process.env.EMCC || 'emcc',
    [
      ...modules.map((m) => 'wasm/freetype/vendor/src/' + m + '.c'),
      'wasm/freetype/system.c',
      'wasm/freetype/bridge.c',
      '-Iwasm/freetype/vendor/include',
      '-Iwasm/freetype/config',
      '-DFT2_BUILD_LIBRARY',
      '-DFT_CONFIG_MODULES_H="ftmodule.h"',
      '-DFT_CONFIG_OPTIONS_H="ftoption.h"',
      '-O2',
      '--no-entry',
      '-sSTANDALONE_WASM=1',
      '-sSUPPORT_LONGJMP=wasm',
      '-mexception-handling',
      '-sALLOW_MEMORY_GROWTH=1',
      '-sINITIAL_MEMORY=16777216',
      '-sMAXIMUM_MEMORY=134217728',
      '-sSTACK_SIZE=1048576',
      '-sFILESYSTEM=0',
      '-sEXPORTED_FUNCTIONS=' + JSON.stringify(exports.map((n) => '_' + n)),
      '-o',
      output,
    ],
    {cwd: root, stdio: 'inherit'},
  );
  if (result.error) throw result.error;
  if (result.status !== 0) throw Error('FreeType wasm build exited ' + result.status);
  const bytes = await readFile(output);
  await writeFile(
    join(root, 'src/text/freetype-wasm-binary.ts'),
    '// Generated by tools/build-freetype.mjs from FreeType 2.4.8. Do not edit.\n// prettier-ignore\nexport const FREETYPE_WASM_BINARY = ' +
      JSON.stringify(bytes.toString('base64')) +
      ';\n',
  );
  console.log('FreeType wasm bytes:', bytes.length);
} finally {
  await rm(dir, {recursive: true, force: true});
}
